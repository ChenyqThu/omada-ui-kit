import type { OmadaProductName } from '@/omada';

export type EmulatorDeviceCategory = 'gateway' | 'switch' | 'ap' | 'olt';
export type EmulatorHealthBucket = 'good' | 'fair' | 'poor' | 'no-data';
export type EmulatorDeviceStatus =
  | 'connected'
  | 'disconnected'
  | 'heartbeat-missed'
  | 'adopt-failed'
  | 'pending'
  | 'provisioning'
  | 'isolated';

export interface EmulatorPortItem {
  port: number;
  name: string;
  linkStatus: '10g' | '2.5g' | '1000m' | '100m' | 'disabled' | 'disconnected';
  isSfp?: boolean;
  isUplink?: boolean;
  isPoe?: boolean;
  isMirroring?: boolean;
  isBlocking?: boolean;
  isLag?: boolean;
  lacp?: string;
  connectionName?: string;
  connectionProductSlug?: string;
  connectionType?: 'gateway' | 'switch' | 'ap' | 'olt' | 'client';
  label?: string;
  type?: string;
  poeCapability?: string;
  profile?: string;
  nativeNetwork?: string;
  txSum?: string;
  rxSum?: string;
}

export interface EmulatorDeviceRecord {
  key: string;
  name: string;
  tag?: 'IP Passthrough' | 'Stack' | 'MLAG';
  model: string;
  productSlug: OmadaProductName;
  category: EmulatorDeviceCategory;
  status: EmulatorDeviceStatus;
  poeWarning?: boolean;
  healthBucket: EmulatorHealthBucket;
  healthScore?: number;
  healthLabel: string;
  mac: string;
  ipv4: string;
  ipv6: string;
  voipVlanIp: string;
  controllerIp: string;
  serialNumber: string;
  customer: 'Headquarters Building';
  firmwareVersion: string;
  firmwareFull: string;
  uptime: string;
  cpu: number;
  memory: number;
  poeUsedW?: number;
  poeTotalW?: number;
  usedPorts?: number;
  totalPorts?: number;
  uplink?: { name: string; port: number };
  downlinks?: Array<{ name: string; port: number }>;
  ports?: EmulatorPortItem[];
}

export interface EmulatorDeviceGroupRecord {
  key: string;
  name: string;
  type: 'AP Group' | 'Switch Stack' | 'Gateway Cluster' | 'All Devices';
  deviceCount: number;
  onlineCount: number;
  site: string;
  description: string;
}

export interface EmulatorConfigResultRecord {
  key: string;
  timestamp: string;
  deviceName: string;
  mac: string;
  configItem: string;
  status: 'Success' | 'Pending';
  duration: string;
}

